using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace VsConan.Core;

/// <summary>
/// The project's CMakeUserPresets.json, which includes each profile's Conan-generated CMakePresets.json.
/// VsConan writes it once after all installs rather than letting Conan update it after each one.
/// </summary>
public static class UserPresetsFile
{
    public static string GetPath(string projectDirectory) =>
        Path.Combine(projectDirectory, "CMakeUserPresets.json");

    /// <summary>
    /// True if the file is missing or was generated by Conan/VsConan. A hand-written file is never
    /// overwritten (Conan follows the same rule).
    /// </summary>
    public static bool CanWrite(string projectDirectory)
    {
        var path = GetPath(projectDirectory);
        if (!File.Exists(path))
        {
            return true;
        }

        try
        {
            return JObject.Parse(File.ReadAllText(path))["vendor"]?["conan"] is not null;
        }
        catch (JsonException)
        {
            return false;
        }
    }

    /// <summary>Paths of the included presets files, resolved against the project directory.</summary>
    public static IReadOnlyList<string> ReadIncludes(string projectDirectory)
    {
        var path = GetPath(projectDirectory);
        if (!File.Exists(path))
        {
            return Array.Empty<string>();
        }

        var include = JObject.Parse(File.ReadAllText(path))["include"] as JArray;
        return include?
            .Select(token => Path.GetFullPath(Path.Combine(projectDirectory, (string)token!)))
            .ToList() ?? new List<string>();
    }

    /// <summary>Names of the configure presets in a Conan-generated CMakePresets.json; empty if it can't be read.</summary>
    public static IReadOnlyList<string> ReadConfigurePresetNames(string presetsFile)
    {
        try
        {
            var presets = JObject.Parse(File.ReadAllText(presetsFile))["configurePresets"] as JArray;
            return presets?
                .Select(preset => (string?)preset["name"])
                .Where(name => !string.IsNullOrEmpty(name))
                .Select(name => name!)
                .ToList() ?? new List<string>();
        }
        catch (Exception ex) when (ex is IOException or JsonException or UnauthorizedAccessException)
        {
            return Array.Empty<string>();
        }
    }

    /// <summary>Configure presets from the files CMakeUserPresets.json currently includes.</summary>
    public static IReadOnlyList<string> CurrentConfigurePresetNames(string projectDirectory) =>
        ReadIncludes(projectDirectory).SelectMany(ReadConfigurePresetNames).ToList();

    /// <summary>Writes the file so it includes exactly <paramref name="presetsFiles"/>.</summary>
    /// <returns>True if the file changed.</returns>
    public static bool Write(string projectDirectory, IEnumerable<string> presetsFiles)
    {
        var document = new JObject
        {
            ["version"] = 4,
            // The "conan" vendor key keeps Conan treating the file as generated, so a manual
            // 'conan install' may still update it.
            ["vendor"] = new JObject { ["conan"] = new JObject() },
            ["include"] = new JArray(presetsFiles.Select(f => ToIncludePath(projectDirectory, f))),
        };

        return AtomicFile.WriteAllTextIfChanged(GetPath(projectDirectory), document.ToString(Formatting.Indented));
    }

    private static string ToIncludePath(string projectDirectory, string file)
    {
        var root = Path.GetFullPath(projectDirectory).TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar;
        var full = Path.GetFullPath(file);
        var path = full.StartsWith(root, StringComparison.OrdinalIgnoreCase) ? full.Substring(root.Length) : full;
        return path.Replace('\\', '/');
    }
}
