using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;

namespace VsConan.Core;

public enum SyncOutcome
{
    /// <summary>The last install is still current; nothing ran.</summary>
    UpToDate,

    /// <summary>Every profile installed and CMakeUserPresets.json is current.</summary>
    Installed,

    /// <summary>At least one profile failed; presets were published for the ones that succeeded.</summary>
    PartiallyFailed,

    /// <summary>A hand-written CMakeUserPresets.json is in the way; nothing ran.</summary>
    UserPresetsNotOwned,
}

public sealed class SyncResult
{
    public SyncResult(SyncOutcome outcome, IReadOnlyList<ProfileInstallResult> profiles)
    {
        Outcome = outcome;
        Profiles = profiles;
    }

    public SyncOutcome Outcome { get; }

    public IReadOnlyList<ProfileInstallResult> Profiles { get; }
}

/// <summary>
/// Brings a project's Conan dependencies up to date before VS's CMake integration uses them.
/// The CMake integration is paused (<see cref="CMakeGate"/>) while Conan runs, and
/// CMakeUserPresets.json is written once at the end, so VS configures once with the final state.
/// </summary>
public sealed class DependencySync
{
    private readonly ConanCli _cli;

    public DependencySync(ConanCli cli)
    {
        _cli = cli;
    }

    public static bool IsUpToDate(ConanProject project, VsConanSettings settings)
    {
        var state = VsConanState.Load(project.RootDirectory);
        if (state.InstallFingerprint != InstallFingerprint.Compute(project, settings))
        {
            return false;
        }

        var includes = UserPresetsFile.ReadIncludes(project.RootDirectory);
        return includes.Count > 0 && includes.All(File.Exists);
    }

    /// <param name="force">Install even if <see cref="IsUpToDate"/>.</param>
    public async Task<SyncResult> RunAsync(
        ConanProject project,
        VsConanSettings settings,
        bool force,
        Action<string> onOutput,
        CancellationToken cancellationToken)
    {
        var directory = project.RootDirectory;
        var gate = new CMakeGate(directory);

        if (!force && IsUpToDate(project, settings))
        {
            gate.Open();
            return new SyncResult(SyncOutcome.UpToDate, Array.Empty<ProfileInstallResult>());
        }

        if (!UserPresetsFile.CanWrite(directory))
        {
            onOutput($"{UserPresetsFile.GetPath(directory)} wasn't generated by Conan, so VsConan won't overwrite it. "
                + "Delete or rename it to let VsConan manage it.");
            gate.Open();
            return new SyncResult(SyncOutcome.UserPresetsNotOwned, Array.Empty<ProfileInstallResult>());
        }

        gate.Close();
        try
        {
            var results = await new ConanInstaller(_cli)
                .InstallAsync(project, settings, onOutput, cancellationToken)
                .ConfigureAwait(false);

            foreach (var result in results.Where(r => r.Succeeded && (r.PresetsFile is null || !File.Exists(r.PresetsFile))))
            {
                onOutput($"Warning: profile '{result.Profile}' produced no CMakePresets.json. "
                    + "Does the conanfile use the CMakeToolchain generator?");
            }

            var presets = results
                .Where(r => r.Succeeded && r.PresetsFile is not null && File.Exists(r.PresetsFile))
                .Select(r => r.PresetsFile!)
                .ToList();

            var allSucceeded = results.All(r => r.Succeeded);
            if (!allSucceeded)
            {
                // Keep the presets of failed profiles from their last good install rather than dropping them.
                presets = UserPresetsFile.ReadIncludes(directory).Where(File.Exists)
                    .Concat(presets)
                    .Distinct(StringComparer.OrdinalIgnoreCase)
                    .ToList();
            }

            UserPresetsFile.Write(directory, presets);

            var state = VsConanState.Load(directory);
            state.InstallFingerprint = allSucceeded ? InstallFingerprint.Compute(project, settings) : null;
            state.Save(directory);

            return new SyncResult(allSucceeded ? SyncOutcome.Installed : SyncOutcome.PartiallyFailed, results);
        }
        finally
        {
            // Resume even on failure: a paused CMake integration with no explanation is worse than VS
            // configuring against the last good presets. Cancellation means the folder is closing or
            // VS is exiting, so stay paused and let the next open finish the install first.
            if (!cancellationToken.IsCancellationRequested)
            {
                gate.Open();
            }
        }
    }
}
